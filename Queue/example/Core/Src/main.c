/*! 
*  \brief  消息处理流程
*  \param msg 待处理消息
*  \param size 消息长度
*/
void ProcessMessage( PCTRL_MSG msg, uint16_t size )
{
    uint8_t cmd_type = msg->cmd_type;         //指令类型
    uint8_t ctrl_msg = msg->ctrl_msg;         //消息的类型
    uint8_t data = msg->data;


    switch(cmd_type){
      case 0:
        break;
      case 1:
        break;
      default:
        OLED_ShowString(1,1,"cmd:");
        OLED_ShowString(2,1,"ctrl:");
        OLED_ShowString(3,1,"data:");
        OLED_ShowHexNum(1,5,cmd_type,2);
        OLED_ShowHexNum(2,6,ctrl_msg,2);
        OLED_ShowHexNum(3,6,data,2);
        break;
    }

}

